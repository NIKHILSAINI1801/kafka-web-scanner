_env = Environment(
    autoescape=True,
    undefined=StrictUndefined,
    trim_blocks=True,
    lstrip_blocks=True,
)
_template = _env.from_string(_TEMPLATE)


def _http_details(result: ScanResult) -> list[tuple[str, str]]:
    details: list[tuple[str, str]] = []
    http = result.http
    if http.get("resolved_ip"):
        details.append(("Resolved address", str(http["resolved_ip"])))
    if http.get("tls_protocol"):
        details.append(("TLS protocol", str(http["tls_protocol"])))
    if "response_bytes_read" in http:
        suffix = " (truncated at the size cap)" if http.get("body_truncated") else ""
        details.append(("Response bytes read", f"{http['response_bytes_read']}{suffix}"))
    return details


def render_html(result: ScanResult) -> str:
    summary = summarize(result.findings)
    status_code = result.status_code
    context: dict[str, Any] = {
        "tool": TOOL_NAME,
        "version": result.tool_version,
        "target": result.target,
        "started": format_utc(result.started_at),
        "finished": format_utc(result.finished_at) if result.finished_at else "n/a",
        "status": result.status,
        "http_status": f"{status_code} {result.http.get('reason', '')}".strip()
        if status_code is not None
        else "n/a",
        "authorization": result.authorization,
        "lab_mode": result.lab_mode,
        "http_details": _http_details(result),
        "counts": [
            {
                "label": severity.value,
                "css": severity.value.lower(),
                "glyph": GLYPHS[severity],
                "count": summary.counts[severity.value],
            }
            for severity in SEVERITY_ORDER
        ],
        "triage": summary.triage,
        "total": summary.total,
        "recommendations": top_recommendations(result.findings),
        "findings": [
            {
                **finding.to_dict(),
                "css": finding.severity.value.lower(),
                "glyph": GLYPHS[finding.severity],
            }
            for finding in sort_findings(result.findings)
        ],
        "errors": result.errors,
        "warnings": result.warnings,
        "limitations": LIMITATIONS,
        "disclaimer": DISCLAIMER,
    }
    return _template.render(context)
